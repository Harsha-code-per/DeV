"""
Markdown Plan Builder

Generates beautiful markdown implementation plans that are:
- Reviewable by users
- Editable before execution
- Verifiable against actual changes
- Archived for future reference
"""

from pathlib import Path
from datetime import datetime
from app.cli.elite_models import ImplementationPlan, TaskType
from app.utils.logger import get_logger

logger = get_logger(__name__)


class MarkdownPlanBuilder:
    """Build markdown implementation plans"""
    
    PLAN_TEMPLATE = """# Implementation Plan

**Generated**: {timestamp}
**Task Type**: {task_type}
**Estimated Time**: {estimated_time}

## Task

{task_description}

## Diagnosis & Hypothesis

{hypothesis}

## Proposed Solution

### Overview
{overview}

### Affected Files
{affected_files_list}

### Proposed Changes

{proposed_changes_list}

## Risk Analysis

{risk_analysis}

## Verification Steps

{verification_steps_list}

## Review Checklist

- [ ] Approach seems correct
- [ ] Changes are minimal/focused
- [ ] Risk level is acceptable
- [ ] Verification steps are comprehensive
- [ ] Ready to execute in isolated sandbox

---

**Notes**: This plan was automatically generated by DeV. You can edit it before execution.
"""
    
    def __init__(self, dev_dir: Path):
        """Initialize plan builder"""
        self.dev_dir = dev_dir
        self.plans_dir = dev_dir / "plans"
    
    def build_and_save(self, plan: ImplementationPlan) -> bool:
        """
        Build and save plan to markdown file
        
        Args:
            plan: ImplementationPlan object
        
        Returns:
            True if successful
        """
        try:
            # Ensure plans directory exists
            self.plans_dir.mkdir(parents=True, exist_ok=True)
            
            # Generate filename
            timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            task_slug = plan.task_description[:30].lower().replace(" ", "-")
            filename = f"{timestamp}-{task_slug}.md"
            
            # Update plan object
            plan.filename = filename
            
            # Generate markdown content
            markdown = self._generate_markdown(plan)
            
            # Write file
            file_path = self.plans_dir / filename
            file_path.write_text(markdown)
            
            logger.info(f"Saved plan to {file_path}")
            return True
        
        except Exception as e:
            logger.error(f"Error saving plan: {e}")
            return False
    
    def _generate_markdown(self, plan: ImplementationPlan) -> str:
        """Generate markdown content from plan"""
        # Format task type
        task_type_str = plan.task_type.value if plan.task_type else "unknown"
        
        # Format estimated time
        if plan.estimated_time_minutes:
            if plan.estimated_time_minutes < 60:
                time_str = f"{plan.estimated_time_minutes} minutes"
            else:
                hours = plan.estimated_time_minutes / 60
                time_str = f"{hours:.1f} hours"
        else:
            time_str = "TBD"
        
        # Format affected files
        if plan.affected_files:
            affected_files_list = "\n".join(
                f"- `{f}`" for f in plan.affected_files
            )
        else:
            affected_files_list = "- TBD (to be determined during execution)"
        
        # Format proposed changes
        if plan.proposed_changes:
            proposed_changes_list = "\n".join(
                f"- {c}" for c in plan.proposed_changes
            )
        else:
            proposed_changes_list = "- TBD (to be determined based on diagnosis)"
        
        # Format risks
        if plan.risks:
            risk_analysis = "\n".join(f"- **{r}**" for r in plan.risks)
        else:
            risk_analysis = "- No significant risks identified"
        
        # Format verification steps
        if plan.verification_steps:
            verification_steps_list = "\n".join(
                f"- [ ] {v}" for v in plan.verification_steps
            )
        else:
            verification_steps_list = "- [ ] Manual verification"
        
        # Fill template
        content = self.PLAN_TEMPLATE.format(
            timestamp=datetime.now().isoformat(),
            task_type=task_type_str,
            estimated_time=time_str,
            task_description=plan.task_description,
            hypothesis=plan.hypothesis,
            overview="See proposed changes below.",
            affected_files_list=affected_files_list,
            proposed_changes_list=proposed_changes_list,
            risk_analysis=risk_analysis,
            verification_steps_list=verification_steps_list,
        )
        
        return content
    
    def read_plan(self, filename: str) -> dict:
        """
        Read plan file and parse it
        
        Args:
            filename: Plan filename
        
        Returns:
            Dict with plan content
        """
        try:
            file_path = self.plans_dir / filename
            if not file_path.exists():
                return None
            
            content = file_path.read_text()
            
            return {
                "filename": filename,
                "content": content,
                "created": file_path.stat().st_mtime,
            }
        except Exception as e:
            logger.warning(f"Error reading plan: {e}")
            return None
    
    def list_recent_plans(self, count: int = 5) -> list:
        """
        List recent plans
        
        Args:
            count: Number of plans to return
        
        Returns:
            List of plan filenames
        """
        try:
            if not self.plans_dir.exists():
                return []
            
            plans = sorted(
                self.plans_dir.glob("*.md"),
                key=lambda p: p.stat().st_mtime,
                reverse=True
            )
            
            return [p.name for p in plans[:count]]
        except Exception as e:
            logger.warning(f"Error listing plans: {e}")
            return []
